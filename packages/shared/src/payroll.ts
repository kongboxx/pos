const nameSchema = z.string().trim().min(1, 'ต้องใส่ชื่อ').max(80, 'ชื่อยาวเกินไป');
const optionalText = (max: number) => z.string().trim().max(max).nullish();

/**
 * A staff member as typed into the management screen.
 *
 * `pin` is separate (see below) and never part of this object — it must not be
 * able to ride along in an update payload that a screen built for editing a
 * phone number, and it must never be echoed back in a response.
 */
const staffFields = z.object({
  fullName: nameSchema,
  nickname: optionalText(40),
  position: optionalText(40),
  role: roleSchema,
  phone: optionalText(20),
  /**
   * Optional and nullable: most people have none, and clearing it is how an
   * account stops being able to reach the back office by username.
   */
  email: emailSchema.nullable().optional(),

  startDate: businessDateSchema,
  endDate: businessDateSchema.nullish(),
  status: staffStatusSchema,

  nationality: nationalitySchema,
  passportNo: optionalText(30),
  passportExpiry: businessDateSchema.nullish(),
  workPermitNo: optionalText(30),
  workPermitExpiry: businessDateSchema.nullish(),

  wageType: wageTypeSchema,
  wageRateSatang: nonNegativeSatangSchema,

  note: optionalText(200),
});

/** Somebody cannot have left before they started. */
const endsAfterStart = {
  check: (value: { startDate: string; endDate?: string | null }) =>
    !value.endDate || value.endDate >= value.startDate,
  options: { message: 'วันที่ออกต้องไม่มาก่อนวันเริ่มงาน', path: ['endDate'] as const },
};

export const staffRequestSchema = staffFields.refine(endsAfterStart.check, {
  ...endsAfterStart.options,
  path: [...endsAfterStart.options.path],
});
export type StaffRequest = z.infer<typeof staffRequestSchema>;

/** Creating someone needs a PIN; editing them leaves the existing one alone. */
export const staffCreateRequestSchema = staffFields
  .extend({ pin: pinSchema })
  .refine(endsAfterStart.check, {
    ...endsAfterStart.options,
    path: [...endsAfterStart.options.path],
  });
export type StaffCreateRequest = z.infer<typeof staffCreateRequestSchema>;

export const staffPinRequestSchema = z.object({ pin: pinSchema });
export type StaffPinRequest = z.infer<typeof staffPinRequestSchema>;

export const staffPasswordRequestSchema = z.object({ password: passwordSchema });
export type StaffPasswordRequest = z.infer<typeof staffPasswordRequestSchema>;

/**
 * A staff member as sent to the screen.
 *
 * Note what is NOT here: pinHash, failedPinAttempts, pinLockedUntil. The hash
 * has no business leaving the server even for an owner — it is the one field
 * that is worth stealing, and a screen that never receives it cannot leak it
 * through a screenshot, a log or a service worker cache.
 */
export const staffDtoSchema = z.object({
  id: uuidSchema,
  fullName: z.string(),
  nickname: z.string().nullable(),
  position: z.string().nullable(),
  role: roleSchema,
  phone: z.string().nullable(),
  /** The back office username. null for everyone who does not have one. */
  email: z.string().nullable(),
  /** Whether a password is set. The hash itself never leaves the API. */
  hasOfficeAccess: z.boolean(),
  /** True while the password lockout is in force, so the screen can say so. */
  isLoginLocked: z.boolean(),

  startDate: businessDateSchema,
  endDate: businessDateSchema.nullable(),
  status: staffStatusSchema,

  nationality: nationalitySchema,
  passportNo: z.string().nullable(),
  passportExpiry: businessDateSchema.nullable(),
  workPermitNo: z.string().nullable(),
  workPermitExpiry: businessDateSchema.nullable(),

  wageType: wageTypeSchema,
  wageRateSatang: nonNegativeSatangSchema,

  note: z.string().nullable(),
  lastLoginAt: z.string().nullable(),
  /** true while the PIN lockout is in force, so the screen can offer a reset. */
  isPinLocked: z.boolean(),
  /**
   * Whether anything in the system points at this person yet. false means the
   * row can still be deleted outright; true means "ลาออก" is the only exit.
   */
  hasHistory: z.boolean(),
});
export type StaffDto = z.infer<typeof staffDtoSchema>;

export const staffListResponseSchema = z.object({
  /** The business date the expiry states below were computed against. */
  today: businessDateSchema,
  staff: z.array(staffDtoSchema),
});
export type StaffListResponse = z.infer<typeof staffListResponseSchema>;

