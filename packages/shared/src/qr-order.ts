/**
 * How long a customer has been waiting for someone to press the button.
 *
 * A pending line is a person sitting at a table looking at their phone, so the
 * clock here is far tighter than the kitchen's. One minute is "nobody has
 * looked yet"; three is long enough that the customer has decided the QR does
 * not work and is waving at a member of staff — which is the entire thing this
 * feature was supposed to prevent.
 */
export const QR_WAIT_WARN_SECONDS = 60;
export const QR_WAIT_LATE_SECONDS = 180;

export type QrWaitUrgency = 'fresh' | 'warn' | 'late';

export function secondsWaiting(submittedAt: Date | string, now: Date = new Date()): number {
  const at = submittedAt instanceof Date ? submittedAt : new Date(submittedAt);
  return Math.max(0, Math.floor((now.getTime() - at.getTime()) / 1000));
}

export function qrWaitUrgency(submittedAt: Date | string, now: Date = new Date()): QrWaitUrgency {
  const seconds = secondsWaiting(submittedAt, now);
  if (seconds >= QR_WAIT_LATE_SECONDS) return 'late';
  if (seconds >= QR_WAIT_WARN_SECONDS) return 'warn';
  return 'fresh';
}

