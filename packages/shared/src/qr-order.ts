/** The zone a table with no zone is shown under. Display only — stored as null. */
export const NO_ZONE_LABEL = 'ไม่ระบุโซน';

/**
 * Groups tables for the editor and the floor plan, in the order they are shown.
 *
 * Zones come out in the order they are FIRST SEEN in the sorted list, which —
 * because the server sorts by zone then sortOrder — is alphabetical by zone.
 * Doing it here rather than in each screen is what keeps the editor's order
 * and the floor plan's order the same thing; two sorts that drift apart would
 * mean the ขึ้น/ลง buttons move a table somewhere it does not visibly move.
 */
export function groupTablesByZone<T extends { zone: string | null }>(
  tables: readonly T[],
): { zone: string; tables: T[] }[] {
  const groups = new Map<string, T[]>();
  for (const table of tables) {
    const key = table.zone ?? NO_ZONE_LABEL;
    const bucket = groups.get(key);
    if (bucket) bucket.push(table);
    else groups.set(key, [table]);
  }
  return [...groups].map(([zone, rows]) => ({ zone, tables: rows }));
}
