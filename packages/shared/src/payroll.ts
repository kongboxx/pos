/**
 * How far ahead a document expiry is worth shouting about.
 *
 * 90 days because renewing a Thai work permit is not a same-week errand, and
 * the shop employing someone whose permit lapsed is the shop's problem, not
 * the employee's. The warning is the entire reason those columns exist.
 */
export const DOCUMENT_WARNING_DAYS = 90;

export type DocumentExpiryState = 'NONE' | 'OK' | 'EXPIRING' | 'EXPIRED';

/** Whole days from one business date to another. Negative = already past. */
export function daysBetween(from: BusinessDate, to: BusinessDate): number {
  assertBusinessDate(from);
  assertBusinessDate(to);
  const MS_PER_DAY = 24 * 60 * 60 * 1000;
  return Math.round((Date.parse(`${to}T00:00:00Z`) - Date.parse(`${from}T00:00:00Z`)) / MS_PER_DAY);
}

/**
 * `EXPIRED` on the day it expires, not the day after.
 *
 * A permit valid "ถึง 15 มีนาคม" is one whose last usable day is the 15th, so
 * treating the 15th itself as still fine is a day of illegal employment. Erring
 * one day early costs nothing; erring one day late is the whole risk.
 */
export function documentExpiryState(
  expiry: BusinessDate | null | undefined,
  today: BusinessDate,
): DocumentExpiryState {
  if (!expiry) return 'NONE';
  const days = daysBetween(today, expiry);
  if (days <= 0) return 'EXPIRED';
  if (days <= DOCUMENT_WARNING_DAYS) return 'EXPIRING';
  return 'OK';
}

