export type MergeRefusal =
  'SAME_BILL' | 'NOT_OPEN' | 'DIFFERENT_DAY' | 'DISCOUNTED' | 'NOTHING_TO_MOVE';

/** The little a merge needs to know about each side. */
export interface MergeCandidate {
  id: string;
  status: string;
  businessDate: string;
  discountSatang: number;
  lines: readonly OrderLineDto[];
}

export type MergeCheck = { ok: true } | { ok: false; refusal: MergeRefusal; message: string };

/**
 * Whether `source` may be poured into `target`.
 *
 * THE DISCOUNT RULE IS THE ONE WORTH ARGUING ABOUT. A discount is an amount a
 * supervisor agreed against ONE bill (see discount.ts) — ฿20 off a ฿100 bill.
 * After a merge that bill does not exist any more, so neither reading is
 * honest: carrying the amount over applies a figure agreed for one total to a
 * different total, and dropping it silently charges the customer ฿20 they were
 * promised they would not pay.
 *
 * So neither. Clear the discount, merge, and let a supervisor put a discount on
 * the bill that now exists. It costs ten seconds and leaves one audit trail
 * that says what was actually agreed, instead of two that describe bills nobody
 * can point at.
 */
export function canMergeBills(target: MergeCandidate, source: MergeCandidate): MergeCheck {
  if (target.id === source.id) {
    return { ok: false, refusal: 'SAME_BILL', message: 'รวมบิลกับตัวเองไม่ได้' };
  }
  if (target.status !== 'OPEN' || source.status !== 'OPEN') {
    return { ok: false, refusal: 'NOT_OPEN', message: 'รวมได้เฉพาะบิลที่ยังเปิดอยู่' };
  }
  if (target.businessDate !== source.businessDate) {
    // Rule #4. Merging across the cutoff would move yesterday's sales into
    // today's takings, and both days' reports would then be wrong.
    return {
      ok: false,
      refusal: 'DIFFERENT_DAY',
      message: 'สองบิลนี้อยู่คนละวันขาย รวมกันไม่ได้',
    };
  }
  if (target.discountSatang > 0 || source.discountSatang > 0) {
    return {
      ok: false,
      refusal: 'DISCOUNTED',
      message: 'บิลที่มีส่วนลดรวมไม่ได้ — ยกเลิกส่วนลดก่อน แล้วค่อยลดใหม่บนบิลที่รวมแล้ว',
    };
  }
  if (source.lines.filter(isLive).length === 0) {
    return {
      ok: false,
      refusal: 'NOTHING_TO_MOVE',
      message: 'บิลที่จะรวมเข้ามาไม่มีรายการ — ยกเลิกบิลนั้นแทน',
    };
  }
  return { ok: true };
}

