/**
 * A table as the layout editor writes it.
 *
 * `qrToken` is NOT here and never will be: the sticker is a printed credential
 * the server issues, and a rename must not change it — otherwise correcting
 * "A1" to "A01" would send somebody round the room peeling stickers off the
 * furniture. Rotating a token is its own deliberate button.
 *
 * `sortOrder` is not here either. It is decided by the ขึ้น/ลง buttons, which
 * renumber a whole zone server-side; letting the form post a number invites
 * two tables with the same one and an order that then depends on the name.
 */
export const tableRequestSchema = z.object({
  name: z.string().trim().min(1, 'ต้องมีชื่อโต๊ะ').max(20, 'ชื่อโต๊ะยาวเกินไป'),
  /**
   * Free text, and NULLABLE. A shop with one room should not be forced to
   * invent a zone name, and the floor plan already handles the null group.
   */
  zone: z
    .string()
    .trim()
    .max(40)
    .nullish()
    .transform((value) => (value ? value : null)),
  /** Only used to label the table on the floor plan. 0 is legal — a counter seat. */
  seats: z.number().int().min(0, 'จำนวนที่นั่งติดลบไม่ได้').max(50, 'ที่นั่งเยอะผิดปกติ'),
  isActive: z.boolean().default(true),
});
export type TableRequest = z.infer<typeof tableRequestSchema>;

