/**
 * Paying a payroll.
 *
 * `paidDate` is a business date the user picks and defaults to today, NOT the
 * last day of the month being paid for. Step 8's P&L is cash basis: the wages
 * hit the month the money actually left the till, which for a payroll run on
 * the 3rd of August is August. Dating it into July to make it "tidy" would
 * silently move a five-figure sum into a month whose figures may already have
 * been read.
 */
