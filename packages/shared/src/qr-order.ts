/* ------------------------------------------------------------------ */
/* the one definition of "nobody has agreed to this yet"               */
/* ------------------------------------------------------------------ */

/**
 * Whether a bill line is still a request rather than a sale.
 *
 * ONE function, imported by the API mapper, the totals and the screens, because
 * three copies of this condition would drift and the symptom would be a bill
 * whose lines and whose total disagree about what is on it.
 */
export function isAwaitingApproval(line: {
  source: OrderLineSource;
  approvedAt: Date | string | null;
}): boolean {
  return line.source === OrderLineSource.QR && line.approvedAt === null;
}

/* ------------------------------------------------------------------ */
/* the token on the sticker                                            */
/* ------------------------------------------------------------------ */

/**
 * What a table's QR token looks like.
 *
 * Generated by the API as 12 random bytes in base64url — 96 bits, 16
 * characters. Short on purpose: every character is more dots in the QR, and a
 * denser code is a code that a cheap phone camera fails to read across a table
 * at dinner-light. A UUID's dashes would cost four characters for nothing.
 *
 * The upper bound is generous so a token rotated by some later tool does not
 * have to match today's generator byte for byte.
 */
export const qrTokenSchema = z.string().regex(/^[A-Za-z0-9_-]{16,64}$/, 'รหัส QR ไม่ถูกต้อง');

/**
 * The URL printed on the sticker.
 *
 * Built from the origin the MANAGEMENT SCREEN is running on, not from a server
 * setting: the server knows it is `localhost:3001`, which is exactly the
 * address a customer's phone cannot reach. Whoever is looking at the browser is
 * already at an address that works from inside the shop.
 */
export function qrOrderUrl(origin: string, token: string): string {
  return `${origin.replace(/\/+$/, '')}/t/${token}`;
}

