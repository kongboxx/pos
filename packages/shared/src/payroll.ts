/**
 * People, what they are owed, and what gets taken off it (Step 9).
 *
 * THE ONE THING THAT MUST NOT BE GOT WRONG HERE IS PAYING SOMETHING TWICE.
 *
 * A deduction is a row that says "หักเงินอ่อง 200 บาท". It has to come off
 * exactly one payslip, ever. The way that is guaranteed is not by dating it
 * carefully — it is by STAMPING it with the payroll line that consumed it, and
 * only at the moment the payroll is actually paid:
 *
 *  - while a payroll is a DRAFT it consumes nothing. Deductions are gathered
 *    fresh every time the screen is opened, so a lateness recorded five minutes
 *    ago shows up without anyone pressing recalculate.
 *  - the moment it is PAID, every deduction it used is stamped and every figure
 *    on it is frozen. The payslip in someone's hand and the row in the database
 *    now say the same thing forever, whatever is edited afterwards.
 *
 * That is also why the wage terms are snapshotted onto the line (rule #7, the
 * same rule that keeps a menu price change off an open bill): giving someone a
 * raise in August must not quietly rewrite the slip they were handed in July.
 *
 * The second thing that must not be got wrong is counting wages twice in the
 * P&L. Wages reach it as ONE Expense row in the ค่าแรง category, created by
 * paying a payroll and flagged `isAutoGenerated` so Step 8's screens refuse to
 * let anyone hand-edit it. If wages are also typed in by hand as an expense,
 * the month is wrong by a full payroll — so the pay screen looks for that and
 * says so before the button is pressed.
 */

