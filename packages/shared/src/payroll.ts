/* what a wage is worth                                                */
/* ------------------------------------------------------------------ */

/**
 * Gross pay for one person for one month.
 *
 * The two wage types are genuinely different shapes, not one with a divisor:
 *
 *  - DAILY is `rate × days`. Days worked is the whole calculation, and a day
 *    not worked is simply a day not counted.
 *  - MONTHLY is the rate, flat. Days worked is recorded on the slip because it
 *    is worth knowing, but it does NOT scale the money — a salaried cook who
 *    took two days off is not paid 29/31 of a salary, they are paid a salary
 *    minus whatever the shop decided to deduct, and that decision belongs in a
 *    deduction row where it is visible and can be argued with.
 *
 * Pro-rating a monthly salary silently would be the same mistake as any other
 * invisible calculation: nobody could tell it from an error.
 */
export function grossSatangFor(
  wageType: WageType,
  wageRateSatang: Satang,
  daysWorked: number,
): Satang {
  assertSatang(wageRateSatang, 'wage rate');
  if (!Number.isInteger(daysWorked) || daysWorked < 0) {
    throw new RangeError(`daysWorked must be a non-negative integer, got ${daysWorked}`);
  }
  if (wageType === WageType.MONTHLY) return wageRateSatang;
  return wageRateSatang * daysWorked;
}

/**
 * What actually goes in the envelope.
 *
 * Returns the raw arithmetic, negative included. Clamping to zero here would
 * turn "we are taking off more than they earned" — which is a conversation
 * someone has to have — into a payslip reading 0.00 with no explanation.
 */
export function netSatangFor(
  grossSatang: Satang,
  bonusSatang: Satang,
  deductSatang: Satang,
): Satang {
  assertSatang(grossSatang, 'gross');
  assertSatang(bonusSatang, 'bonus');
  assertSatang(deductSatang, 'deduction');
  return grossSatang + bonusSatang - deductSatang;
}

/**
 * true when the deductions swallow the whole wage.
 *
 * The payroll refuses to be paid in this state. There is no carry-forward
 * table in this Step, so the alternative would be either a negative payslip or
 * a balance quietly written off — and the honest fix (shrink the deduction and
 * record the rest next month) is one the owner has to make deliberately.
 */
export function deductionExceedsPay(
  grossSatang: Satang,
  bonusSatang: Satang,
  deductSatang: Satang,
): boolean {
  return netSatangFor(grossSatang, bonusSatang, deductSatang) < 0;
}

