/**
 * Whether somebody belongs on a given month's payroll run.
 *
 * DECIDED BY DATES, NOT BY STATUS, and that distinction is the whole point.
 * The obvious rule — "everyone whose status is not ลาออกแล้ว" — quietly
 * underpays a real person: mark someone as having left on 20 August and
 * August's run drops them, along with the twenty days they actually worked.
 * The owner is looking at a total, not at a headcount, so nothing on the screen
 * says a name is missing.
 *
 * So:
 *  - hired after the month ended  → not on it (a new cook does not get paid for
 *    the month before they arrived).
 *  - left before the month began  → not on it.
 *  - left DURING the month        → on it, and their days settle up.
 *
 * Status is only consulted when there is no leaving date to reason with, which
 * is the one case where it is the sole piece of information available.
 */
export function isOnPayrollForMonth(
  person: {
    status: StaffStatus;
    startDate: BusinessDate;
    endDate?: BusinessDate | null;
  },
  yearMonth: string,
): boolean {
  const [start, endExclusive] = payrollMonthBounds(yearMonth);
  // YYYY-MM-DD compares lexicographically in date order, so no parsing.
  if (person.startDate >= endExclusive) return false;
  if (person.endDate) return person.endDate >= start;
  return person.status !== StaffStatus.LEFT;
}

/** `[first day, first day of next month)` — kept here so this file has no cycle. */
function payrollMonthBounds(yearMonth: string): [BusinessDate, BusinessDate] {
  const [year, month] = yearMonth.split('-').map(Number) as [number, number];
  const next = month === 12 ? `${year + 1}-01` : `${year}-${String(month + 1).padStart(2, '0')}`;
  return [`${yearMonth}-01`, `${next}-01`];
}

