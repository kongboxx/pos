/**
 * The customer's phone (Step 7).
 *
 * A sticker on the table carries a URL. The customer scans it, sees the menu,
 * taps a bowl, and sends it. NOTHING they send reaches the kitchen on its own:
 * every line lands on the bill marked `source = QR` with `approvedAt = null`,
 * and a member of staff has to press "อนุมัติ" before a cook ever sees it.
 *
 * THAT APPROVAL STEP IS THE WHOLE SECURITY MODEL, and it is why the rest of
 * this file can stay as simple as it is.
 *
 * The token in the URL is the only credential a customer has, and it is printed
 * on a sticker in a public room — so it must be assumed to leak. A photograph
 * of the sticker therefore buys exactly one thing: the ability to put a request
 * in a queue that a human reads. Not a bill, not a kitchen ticket, not a price.
 * Trying to make the token itself secret (rotating it per sitting) was the
 * original plan and it does not survive contact with a printed sticker; see the
 * note on DiningTable.qrToken in schema.prisma.
 *
 * Two consequences run through everything below:
 *
 *  1. A PENDING LINE IS NOT MONEY. It is excluded from the bill total, from the
 *     printed check and from the receipt, and the bill cannot be paid while one
 *     is outstanding. The shop has not agreed to sell anything yet.
 *  2. NOTHING HERE CARRIES COST. The customer endpoints are unauthenticated, so
 *     a field that is merely "not displayed" is a field that is published.
 */

