export const BILL_MOVE_ACTIONS = {
  MOVE_TABLE: 'ORDER_MOVE_TABLE',
  MERGE: 'ORDER_MERGE',
  SPLIT: 'ORDER_SPLIT',
} as const;

/** "ย้ายจากโต๊ะ A1 ไปโต๊ะ B2" — readable a month later without joining anything. */
export function describeTableMove(fromTable: string | null, toTable: string): string {
  return fromTable ? `ย้ายจากโต๊ะ ${fromTable} ไปโต๊ะ ${toTable}` : `ย้ายไปโต๊ะ ${toTable}`;
}

/** "รวมบิล 260730-002 (3 รายการ) เข้ากับ 260730-001" */
export function describeMerge(sourceLabel: string, targetLabel: string, lineCount: number): string {
  return `รวมบิล ${sourceLabel} (${lineCount} รายการ) เข้ากับ ${targetLabel}`;
}

/** "แยก 2 รายการออกจากบิล 260730-001 ไปบิลใหม่" */
export function describeSplit(sourceLabel: string, lineCount: number): string {
  return `แยก ${lineCount} รายการออกจากบิล ${sourceLabel} ไปบิลใหม่`;
}
